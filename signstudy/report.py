"""Build every table, figure and number used in the paper from results/raw/. Nothing is typed by hand.

Outputs: results/tables/*.csv|md|tex, figures/*.pdf|png, paper/numbers.tex (one \\newcommand per number in the text),
CLAIMS.md (claims ledger: number -> source file -> script -> commit).
"""
import json
import subprocess
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from . import config as C
from . import stats as S

RAW = C.RESULTS / "raw" / "test"
TABLES = C.RESULTS / "tables"
OKABE = {"dtw1nn": "#0072B2", "euclid1nn": "#999999", "dba_proto": "#56B4E9", "cnn1d": "#D55E00",
         "bigru": "#009E73", "transformer": "#CC79A7", "bigru_aug": "#E69F00"}
MARK = {"dtw1nn": "o", "euclid1nn": "s", "dba_proto": "^", "cnn1d": "v", "bigru": "D", "transformer": "P", "bigru_aug": "X"}
LABEL = {"dtw1nn": "DTW 1-NN", "euclid1nn": "Euclidean 1-NN", "dba_proto": "DBA prototype", "cnn1d": "1D-CNN",
         "bigru": "BiGRU", "transformer": "Transformer", "bigru_aug": "BiGRU + aug."}
K_ORDER = [1, 2, 5, 10, 20, "full"]


def _commit():
    return subprocess.run(["git", "-C", str(C.ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()


def load_main():
    parts = []
    for f in sorted(RAW.glob("*.csv.gz")):
        if "training_time" in f.name or f.name.startswith("ablation"):
            continue
        d = pd.read_csv(f)
        d["file"] = f.name
        parts.append(d)
    df = pd.concat(parts, ignore_index=True)
    df["k"] = df["k"].astype(str)
    df["seed"] = df["seed"].fillna(-1).astype(int)
    return df


def kfmt(k):
    return "full" if str(k) == "full" else str(int(float(k)))


class Ledger:
    def __init__(self):
        self.rows, self.macros = [], {}

    def add(self, macro, value, text, source, fmt="{:.1f}"):
        self.macros[macro] = fmt.format(value) if isinstance(value, (int, float, np.floating)) else str(value)
        self.rows.append((macro, self.macros[macro], text, source))

    def write(self, commit):
        (C.ROOT / "paper").mkdir(exist_ok=True)
        (C.ROOT / "paper" / "numbers.tex").write_text(
            "% generated by signstudy/report.py - do not edit\n" +
            "".join(f"\\newcommand{{\\{m}}}{{{v}}}\n" for m, v in self.macros.items()))
        lines = ["# Claims ledger\n", "Every number in the paper text is a macro defined in `paper/numbers.tex`, generated by",
                 "`python -m signstudy.report` from the files in `results/`. Nothing in the text is typed by hand.\n",
                 f"Generated at commit `{commit}`.\n", "| macro | value | claim | results file | script |", "|---|---|---|---|---|"]
        for m, v, t, s in self.rows:
            lines.append(f"| `{m}` | {v} | {t} | `{s}` | `signstudy/report.py` @ `{commit}` |")
        (C.ROOT / "CLAIMS.md").write_text("\n".join(lines) + "\n")


def pct(x):
    return 100 * x


def main_table(tab, ci, led):
    d = ci[(ci.fset == "F1") & (ci.missing == "zero") & (~ci.dominant)].copy()
    d["cell"] = d.apply(lambda r: f"{pct(r.acc):.1f} [{pct(r.lo):.1f}, {pct(r.hi):.1f}]", axis=1)
    TABLES.mkdir(parents=True, exist_ok=True)
    d.to_csv(TABLES / "main_top1.csv", index=False)
    md = []
    for v in sorted(d.vocab.unique()):
        p = d[d.vocab == v].pivot(index="method", columns="k", values="cell")
        p = p[[str(k) for k in K_ORDER if str(k) in p.columns]]
        md.append(f"### Vocabulary {v}, top-1 accuracy % (95% signer-cluster CI)\n\n" + p.to_markdown() + "\n")
    (TABLES / "main_top1.md").write_text("\n".join(md))
    return d


def figure_main(ci, vocabs):
    d = ci[(ci.fset == "F1") & (ci.missing == "zero") & (~ci.dominant)]
    fig, axes = plt.subplots(1, len(vocabs), figsize=(4.2 * len(vocabs), 3.6), sharey=True, squeeze=False)
    for ax, v in zip(axes[0], vocabs):
        for m in LABEL:
            g = d[(d.vocab == v) & (d.method == m)]
            if g.empty:
                continue
            g = g.assign(ki=g.k.map({str(k): i for i, k in enumerate(K_ORDER)})).sort_values("ki")
            ax.errorbar(g.ki + (list(LABEL).index(m) - 3) * 0.04, pct(g.acc), yerr=[pct(g.acc - g.lo), pct(g.hi - g.acc)],
                        color=OKABE[m], marker=MARK[m], ms=4, lw=1.2, capsize=2, label=LABEL[m])
        ax.set_xticks(range(len(K_ORDER)), [kfmt(k) for k in K_ORDER])
        ax.set_xlabel("references per sign (k)")
        ax.set_title(f"{v} signs")
        ax.grid(alpha=0.3)
    axes[0][0].set_ylabel("top-1 accuracy (%)")
    axes[0][-1].legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    C.FIGURES.mkdir(exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(C.FIGURES / f"accuracy_vs_k.{ext}", dpi=200)
    plt.close(fig)


def hypotheses(tab, led, vocab):
    """H1 / H2 from PREREG.md section 6, plus the multiplicity-adjusted interval for H2."""
    rows = []
    models = [m for m in ("cnn1d", "bigru", "transformer") if m in set(tab.method)]
    where = lambda k: dict(vocab=vocab, k=str(k), fset="F1", missing="zero", dominant=False)
    for m in models:
        for k in (1, 2, 5):
            r = S.paired_difference(tab, "dtw1nn", m, where(k), conf=0.975)
            if r:
                rows.append(dict(hyp="H1", **r))
        r = S.paired_difference(tab, m, "dtw1nn", where("full"), conf=0.975)
        r2 = S.paired_difference(tab, m, "dtw1nn", where("full"), conf=1 - 0.025 / 3)
        if r:
            rows.append(dict(hyp="H2", **r))
            rows.append(dict(hyp="H2 (adjusted for 3 models)", **r2))
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df.to_csv(TABLES / "hypotheses.csv", index=False)
    h1 = df[df.hyp == "H1"]
    h2 = df[df.hyp == "H2"]
    led.add("hOneSupported", "yes" if (len(h1) and (h1.lo > 0).all()) else "no",
            f"H1 supported at vocabulary {vocab}: DTW above every learned model for k in 1,2,5 (97.5% intervals exclude 0)",
            "results/tables/hypotheses.csv", fmt="{}")
    led.add("hTwoSupported", "yes" if (len(h2) and (h2.lo > 0).any()) else "no",
            f"H2 supported at vocabulary {vocab}: some learned model above DTW at k=full (97.5% interval excludes 0)",
            "results/tables/hypotheses.csv", fmt="{}")
    return df


def crossover(ci, led):
    d = ci[(ci.fset == "F1") & (ci.missing == "zero") & (~ci.dominant)]
    rows = []
    for v in sorted(d.vocab.unique()):
        for k in K_ORDER:
            a = d[(d.vocab == v) & (d.k == str(k)) & (d.method == "dtw1nn")]
            ml = d[(d.vocab == v) & (d.k == str(k)) & d.method.isin(["cnn1d", "bigru", "transformer"])]
            if a.empty or ml.empty:
                continue
            best = ml.sort_values("acc").iloc[-1]
            rows.append(dict(vocab=v, k=str(k), dtw=a.acc.iloc[0], best_learned=best.acc, best_method=best.method,
                             learned_ahead=bool(best.acc >= a.acc.iloc[0])))
    df = pd.DataFrame(rows)
    df.to_csv(TABLES / "crossover.csv", index=False)
    for v in sorted(df.vocab.unique()):
        g = df[df.vocab == v]
        ahead = [k for k in map(str, K_ORDER) if k in set(g.k) and bool(g[g.k == k].learned_ahead.iloc[0])]
        led.add(f"crossoverV{v}", ahead[0] if ahead else "none",
                f"smallest k where the best learned model's point estimate is at least DTW's, vocabulary {v} (exploratory)",
                "results/tables/crossover.csv", fmt="{}")
    return df


def ablation_table(led):
    f = C.RESULTS / "raw" / "test" / "ablation.csv.gz"
    if not f.exists():
        return None
    df = pd.read_csv(f)
    df["k"] = df["k"].astype(str)
    df["seed"] = df["seed"].fillna(-1).astype(int)
    ci = S.accuracy_ci(S.signer_table(df))
    ci["setting"] = ci.apply(lambda r: f"{r.fset}/{r.missing}/{'dominant' if r.dominant else 'slots'}", axis=1)
    ci["cell"] = ci.apply(lambda r: f"{pct(r.acc):.1f} [{pct(r.lo):.1f}, {pct(r.hi):.1f}]", axis=1)
    ci.to_csv(TABLES / "ablation.csv", index=False)
    p = ci.pivot_table(index="setting", columns=["method", "k"], values="cell", aggfunc="first")
    (TABLES / "ablation.md").write_text(p.to_markdown())
    return ci


def per_sign(df, vocab, signs):
    d = df[(df.method == "dtw1nn") & (df.vocab == vocab) & (df.k == "full") & (df.fset == "F1")]
    if d.empty:
        return
    acc = d.groupby("sign").apply(lambda g: (g["rank"] <= 1).mean(), include_groups=False).rename("top1").reset_index()
    acc["sign_name"] = [signs[i] for i in acc.sign]
    acc.sort_values("top1").to_csv(TABLES / "per_sign_dtw_full.csv", index=False)
    wrong = d[(d["rank"] > 1) & (d.pred >= 0)]
    conf = wrong.groupby(["sign", "pred"]).size().rename("n").reset_index().sort_values("n", ascending=False).head(20)
    conf["true"] = [signs[i] for i in conf.sign]
    conf["predicted"] = [signs[i] for i in conf.pred]
    conf[["true", "predicted", "n"]].to_csv(TABLES / "top_confusions_dtw_full.csv", index=False)


def timing_table():
    parts = [pd.read_csv(f) for f in sorted((C.RESULTS / "timing").glob("latency_threads*.csv"))]
    if not parts:
        return None
    t = pd.concat(parts)
    t.to_csv(TABLES / "latency.csv", index=False)
    (TABLES / "latency.md").write_text(t.round(3).to_markdown(index=False))
    return t


def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    led = Ledger()
    df = load_main()
    signs = C.sign_list()
    tab = S.signer_table(df)
    ci = S.accuracy_ci(tab)
    ci.to_csv(TABLES / "all_conditions.csv", index=False)
    d = main_table(tab, ci, led)
    vocabs = sorted(d.vocab.unique())
    figure_main(ci, vocabs)
    v50 = 50 if 50 in vocabs else max(vocabs)
    hypotheses(tab, led, v50)
    crossover(ci, led)
    ablation_table(led)
    per_sign(df, max(vocabs), signs)
    timing_table()
    led.add("nVocabMax", max(vocabs), "largest vocabulary evaluated", "results/tables/main_top1.csv", fmt="{:d}")
    led.add("nTestSigners", int(tab.signer.nunique()), "test signers (bootstrap clusters)", "results/raw/test/dtw1nn.csv.gz", fmt="{:d}")
    for m in ("dtw1nn", "euclid1nn", "cnn1d", "bigru", "transformer", "dba_proto"):
        for v in vocabs:
            for k in map(str, K_ORDER):
                r = d[(d.method == m) & (d.vocab == v) & (d.k == k)]
                if not r.empty:
                    r = r.iloc[0]
                    key = f"{m}V{v}K{k}".replace("_", "")
                    led.add(f"acc{key}", pct(r.acc), f"top-1 %, {m}, vocabulary {v}, k={k}", "results/tables/main_top1.csv")
                    led.add(f"lo{key}", pct(r.lo), f"95% CI lower, {m}, vocabulary {v}, k={k}", "results/tables/main_top1.csv")
                    led.add(f"hi{key}", pct(r.hi), f"95% CI upper, {m}, vocabulary {v}, k={k}", "results/tables/main_top1.csv")
    led.write(_commit())
    print("report written:", len(led.rows), "numbers")


if __name__ == "__main__":
    main()
