def nm(prefix, method, v, k):
    """Letter-only LaTeX macro name, e.g. accCnnVFiftyKOne."""
    return f"{prefix}{MW[method]}V{NUMW[int(v)]}K{KW[str(k)]}"


def _commit():
    return subprocess.run(["git", "-C", str(C.ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()


def load_main():
    parts = []
    for f in sorted(RAW.glob("*.csv.gz")):
        if "training_time" in f.name or f.name.startswith("ablation"):
            continue
        d = pd.read_csv(f)
        d["file"] = f.name
        parts.append(d)
    df = pd.concat(parts, ignore_index=True)
    df["k"] = df["k"].astype(str)
    df["seed"] = df["seed"].fillna(-1).astype(int)
    return df


def kfmt(k):
    return "full" if str(k) == "full" else str(int(float(k)))


class Ledger:
    def __init__(self):
        self.rows, self.macros = [], {}

    def add(self, macro, value, text, source, fmt="{:.1f}"):
        assert macro.isalpha(), f"macro name must be letters only: {macro}"
        new = fmt.format(value) if isinstance(value, (int, float, np.floating)) else str(value)
        assert self.macros.get(macro, new) == new, f"duplicate macro with different value: {macro}"
        self.macros[macro] = new
        self.rows.append((macro, self.macros[macro], text, source))

    def write(self, commit):
        (C.ROOT / "paper").mkdir(exist_ok=True)
        (C.ROOT / "paper" / f"numbers{SUF}.tex").write_text(
            "% generated by signstudy/report.py - do not edit\n" +
            "".join(f"\\newcommand{{\\{m}}}{{{v}}}\n" for m, v in self.macros.items()))
        lines = ["# Claims ledger\n", "Every number in the paper text is a macro defined in `paper/numbers.tex`, generated by",
                 "`python -m signstudy.report` from the files in `results/`. Nothing in the text is typed by hand.\n",
                 f"Generated at commit `{commit}`.\n", "| macro | value | claim | results file | script |", "|---|---|---|---|---|"]
        for m, v, t, s in self.rows:
            lines.append(f"| `{m}` | {v} | {t} | `{s}` | `signstudy/report.py` @ `{commit}` |")
        (C.ROOT / f"CLAIMS{SUF}.md").write_text("\n".join(lines) + "\n")


def pct(x):
    return 100 * x


def main_table(tab, ci, led):
    d = ci[(ci.fset == "F1") & (~ci.dominant)].copy()
    d["cell"] = d.apply(lambda r: f"{pct(r.acc):.1f} [{pct(r.lo):.1f}, {pct(r.hi):.1f}]", axis=1)
    TABLES.mkdir(parents=True, exist_ok=True)
    d.to_csv(TABLES / "main_top1.csv", index=False)
    md = []
    for v in sorted(d.vocab.unique()):
        p = d[d.vocab == v].pivot(index="method", columns="k", values="cell")
        p = p[[str(k) for k in K_ORDER if str(k) in p.columns]]
        md.append(f"### Vocabulary {v}, top-1 accuracy % (95% signer-cluster CI)\n\n" + p.to_markdown() + "\n")
    (TABLES / "main_top1.md").write_text("\n".join(md))
    return d


def figure_main(ci, vocabs):
    d = ci[(ci.fset == "F1") & (~ci.dominant)]
    fig, axes = plt.subplots(1, len(vocabs), figsize=(4.2 * len(vocabs), 3.6), sharey=True, squeeze=False)
    for ax, v in zip(axes[0], vocabs):
        for m in LABEL:
            g = d[(d.vocab == v) & (d.method == m)]
            if g.empty:
                continue
            g = g.assign(ki=g.k.map({str(k): i for i, k in enumerate(K_ORDER)})).sort_values("ki")
            ax.errorbar(g.ki + (list(LABEL).index(m) - 3) * 0.04, pct(g.acc), yerr=[pct(g.acc - g.lo), pct(g.hi - g.acc)],
                        color=OKABE[m], marker=MARK[m], ms=4, lw=1.2, capsize=2, label=LABEL[m])
        ax.set_xticks(range(len(K_ORDER)), [kfmt(k) for k in K_ORDER])
        ax.set_xlabel("references per sign (k)")
        ax.set_title(f"{v} signs")
        ax.grid(alpha=0.3)
    axes[0][0].set_ylabel("top-1 accuracy (%)")
    axes[0][-1].legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    C.FIGURES.mkdir(exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(C.FIGURES / f"accuracy_vs_k{SUF}.{ext}", dpi=200)
    plt.close(fig)


def hypotheses(tab, led, vocab):
    """H1 / H2 from PREREG.md section 6, plus the multiplicity-adjusted interval for H2."""
    rows = []
    models = [m for m in ("cnn1d", "bigru", "transformer") if m in set(tab.method)]
    where = lambda k: dict(vocab=vocab, k=str(k), fset="F1", dominant=False)
    for m in models:
        for k in (1, 2, 5):
            r = S.paired_difference(tab, "dtw1nn", m, where(k), conf=0.975)
            if r:
                rows.append(dict(hyp="H1", **r))
        r = S.paired_difference(tab, m, "dtw1nn", where("full"), conf=0.975)
        r2 = S.paired_difference(tab, m, "dtw1nn", where("full"), conf=1 - 0.025 / 3)
        if r:
            rows.append(dict(hyp="H2", **r))
            rows.append(dict(hyp="H2 (adjusted for 3 models)", **r2))
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df.to_csv(TABLES / "hypotheses.csv", index=False)
    h1 = df[df.hyp == "H1"]
    h2 = df[df.hyp == "H2"]
    led.add("hOneSupported", "yes" if (len(h1) and (h1.lo > 0).all()) else "no",
            f"H1 supported at vocabulary {vocab}: DTW above every learned model for k in 1,2,5 (97.5% intervals exclude 0)",
            "results/tables/hypotheses.csv", fmt="{}")
    adj = df[df.hyp.str.startswith("H2 (adj")]
    led.add("hTwoAdjSupported", "yes" if (len(adj) and (adj.lo > 0).all()) else "no",
            "H2 interval still excludes 0 for every learned model after adjusting for 3 models (99.17%)", "results/tables/hypotheses.csv", fmt="{}")
    led.add("nHOneBelowZero", int(((h1.hi < 0)).sum()), "H1 comparisons (k=1,2,5 x 3 models) whose 97.5% interval lies wholly below 0 (DTW below the learned model)", "results/tables/hypotheses.csv", fmt="{:d}")
    led.add("hTwoSupported", "yes" if (len(h2) and (h2.lo > 0).any()) else "no",
            f"H2 supported at vocabulary {vocab}: some learned model above DTW at k=full (97.5% interval excludes 0)",
            "results/tables/hypotheses.csv", fmt="{}")
    return df


def crossover(ci, led):
    d = ci[(ci.fset == "F1") & (~ci.dominant)]
    rows = []
    for v in sorted(d.vocab.unique()):
        for k in K_ORDER:
            a = d[(d.vocab == v) & (d.k == str(k)) & (d.method == "dtw1nn")]
            ml = d[(d.vocab == v) & (d.k == str(k)) & d.method.isin(["cnn1d", "bigru", "transformer"])]
            if a.empty or ml.empty:
                continue
            best = ml.sort_values("acc").iloc[-1]
            rows.append(dict(vocab=v, k=str(k), dtw=a.acc.iloc[0], best_learned=best.acc, best_method=best.method,
                             learned_ahead=bool(best.acc >= a.acc.iloc[0])))
    df = pd.DataFrame(rows)
    df.to_csv(TABLES / "crossover.csv", index=False)
    for v in sorted(df.vocab.unique()):
        g = df[df.vocab == v]
        ahead = [k for k in map(str, K_ORDER) if k in set(g.k) and bool(g[g.k == k].learned_ahead.iloc[0])]
        led.add(f"crossover{NUMW[int(v)]}", ahead[0] if ahead else "none",
                f"smallest k where the best learned model's point estimate is at least DTW's, vocabulary {v} (exploratory)",
                "results/tables/crossover.csv", fmt="{}")
    return df


def paired_table(tab, led, vocabs):
    """Exploratory paired differences against DTW 1-NN at every vocabulary and k (95% intervals)."""
    rows = []
    for v in vocabs:
        for k in map(str, K_ORDER):
            where = dict(vocab=v, k=k, fset="F1", dominant=False)
            for m in ("euclid1nn", "cnn1d", "bigru", "transformer"):
                r = S.paired_difference(tab, m, "dtw1nn", where, conf=0.95)
                if r:
                    rows.append(r)
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df.to_csv(TABLES / "paired_vs_dtw.csv", index=False)
    learned = df[df.a != "euclid1nn"]
    led.add("nPairedLearned", len(learned), "paired comparisons of a learned model with DTW (3 models x k x vocabulary)", "results/tables/paired_vs_dtw.csv", fmt="{:d}")
    led.add("nPairedLearnedExcl", int(((learned.lo > 0) | (learned.hi < 0)).sum()), "of those, 95% intervals excluding zero", "results/tables/paired_vs_dtw.csv", fmt="{:d}")
    led.add("nPairedLearnedAhead", int((learned["diff"] > 0).sum()), "of those, learned model's point estimate above DTW", "results/tables/paired_vs_dtw.csv", fmt="{:d}")
    for r in df.itertuples():
        led.add(nm("dif", r.a, r.vocab, r.k), pct(r.diff), f"{r.a} minus dtw1nn, top-1 percentage points, vocabulary {r.vocab}, k={r.k} (exploratory)", "results/tables/paired_vs_dtw.csv")
        led.add(nm("difLo", r.a, r.vocab, r.k), pct(r.lo), f"lower 95% bound of the same difference", "results/tables/paired_vs_dtw.csv")
        led.add(nm("difHi", r.a, r.vocab, r.k), pct(r.hi), f"upper 95% bound of the same difference", "results/tables/paired_vs_dtw.csv")
    return df


def latex_tables(d):
    """Compact LaTeX tables (accuracy only; intervals are in the CSV and the paired-difference table)."""
    order = [m for m in LABEL if m in set(d.method)]
    for v in sorted(d.vocab.unique()):
        p = d[(d.vocab == v) & d.method.isin(order)].pivot(index="method", columns="k", values="acc")
        p = p.reindex(order)
        cols = [str(k) for k in K_ORDER if str(k) in p.columns]
        lines = ["\\begin{tabular}{l" + "r" * len(cols) + "}", "\\toprule",
                 "Method & " + " & ".join("all" if c == "full" else c for c in cols) + " \\\\", "\\midrule"]
        for m in order:
            lines.append(LABEL[m] + " & " + " & ".join("--" if pd.isna(p.loc[m, c]) else f"{pct(p.loc[m, c]):.1f}" for c in cols) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        (TABLES / f"main_v{v}.tex").write_text("\n".join(lines) + "\n")


def tuning_table(led):
    """Validation grid behind the per-family choices (documents how much preprocessing matters)."""
    f = C.RESULTS / "tuned.json"
    if not f.exists():
        return None
    t = json.loads(f.read_text())
    rows = []
    for fam, grid in t["grids"].items():
        for cfg, acc in grid:
            rows.append(dict(family=fam, **cfg, val_top1=acc))
    df = pd.DataFrame(rows)
    df.to_csv(TABLES / "tuning_validation.csv", index=False)
    name = {"dtw": "Dtw", "euclid": "Euclid", "cnn1d": "Cnn", "bigru": "Gru", "transformer": "Trans"}
    for fam, g in df.groupby("family"):
        led.add(f"tuneBest{name[fam]}", pct(g.val_top1.max()), f"validation top-1 of the chosen {fam} configuration (vocabulary {t['n_tune']}, k=10)", "results/tuned.json")
        led.add(f"tuneZero{name[fam]}", pct(g[g.missing == "zero"].val_top1.max()), f"best validation top-1 of {fam} with zero-filled missing hands", "results/tuned.json")
        led.add(f"tuneWorst{name[fam]}", pct(g.val_top1.min()), f"worst validation top-1 in the {fam} grid", "results/tuned.json")
    ch = df[df.family == "dtw"].val_top1.max()
    nv = df[(df.family == "dtw") & (df.missing == "zero") & (df.scale == "raw") & (df.radius == -1)].val_top1
    if len(nv):
        led.add("tuneGapDtw", pct(ch - nv.iloc[0]), "validation top-1 gain of the chosen DTW configuration over the naive default, percentage points", "results/tuned.json")
    naive = df[(df.family == "dtw") & (df.missing == "zero") & (df.scale == "raw") & (df.radius == -1)].val_top1
    if len(naive):
        led.add("tuneNaiveDtw", pct(naive.iloc[0]), "validation top-1 of DTW with zero-fill, raw scale, unconstrained", "results/tuned.json")
    return df


